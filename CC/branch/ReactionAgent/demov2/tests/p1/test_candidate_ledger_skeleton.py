"""P1-T8 CandidateAnalogyLedger skeleton — invariant tests.

Tests define the contract for:
- ``build_candidate_skeleton(source_ledger, adaptation, *, candidate_id)``
  -> CandidateAnalogyLedger — builds the candidate analogy ledger skeleton
  from a SourceReactionLedger + QueryCandidateAdaptation + caller-provided
  candidate_id (current context).

Design references (final_design §14, ADR-0003):
- §14: CandidateAnalogyLedger records donor-derived analogy assumptions for
  X→Y. Donor cofactors/stoichiometry do NOT become proven facts about X→Y.
- 5 key invariants (§14):
  1. donor_context_is_assumption = True (InheritedDonorContext.is_assumption
     locked to True by the schema; builder must populate contexts).
  2. source_ledger_link exists (source_ledger_id mandatory, matches input).
  3. candidate_id belongs current context (caller-provided, non-empty,
     echoed back verbatim — NOT generated by the builder).
  4. donor cofactor != proven X→Y cofactor (donor cofactors flow to
     unknown_actual_cofactors, never to a "proven cofactors" field).
  5. formal_balance_under_assumptions != observed balance (separate object,
     explicitly labeled as assumption-based; candidate_balance_status
     defaults to partial_or_unbalanced_source).

No-fabrication discipline (brief §14):
- Skeleton does NOT generate Y (no product SMILES, no Candidate.canonical_product).
- Skeleton does NOT produce candidate ranking (no ranking_score).
- Skeleton does NOT produce LLM rationale (no rationale/llm_rationale field).
- Fixture candidates are NOT predictions (skeleton only — the candidate_id is
  a context handle, not a generated product).

Zero-skip: no ``@pytest.mark.skipif``. Preflight BLOCKED (rdkit absent) does
not affect T8 — the skeleton inherits donor context as assumptions and does
not compute real element balance (that is the source ledger's job in T7).
"""
from __future__ import annotations

import pytest
from pydantic import ValidationError

from reaction_agent.schemas.common import (
    LedgerBalanceStatus,
    ParticipantRole,
)
from reaction_agent.schemas.ledger import (
    CandidateAnalogyLedger,
    CofactorChange,
    FormalBalanceUnderAssumptions,
    InheritedDonorContext,
    QueryCandidateAdaptation,
    RoleAssignment,
    SourceReactionLedger,
    StoichiometricEntry,
)
from reaction_agent.ledgers.candidate_builder import build_candidate_skeleton


# =====================================================================
# Fixture helpers (all synthetic / curated — no real data fabricated)
# =====================================================================

def _minimal_source_ledger(
    *,
    ledger_id: str = "srl_test_001",
    reaction_evidence_id: str = "rxn_001",
    cofactor_changes: list[CofactorChange] | None = None,
    role_assignments: list[RoleAssignment] | None = None,
    stoichiometry: list[StoichiometricEntry] | None = None,
    balance_status: LedgerBalanceStatus = LedgerBalanceStatus.partial_or_unbalanced_source,
) -> SourceReactionLedger:
    """Build a minimal SourceReactionLedger for candidate skeleton tests.

    Unit-style: constructs the ledger directly (not via build_source_ledger)
    so T8 tests do not depend on T7 internals. Only the fields the candidate
    builder reads are populated; everything else uses schema defaults.
    """
    kwargs: dict = {
        "ledger_id": ledger_id,
        "reaction_evidence_id": reaction_evidence_id,
        "balance_status": balance_status,
    }
    if cofactor_changes is not None:
        kwargs["cofactor_changes"] = cofactor_changes
    if role_assignments is not None:
        kwargs["role_assignments"] = role_assignments
    if stoichiometry is not None:
        kwargs["stoichiometry"] = stoichiometry
    return SourceReactionLedger(**kwargs)


def _adaptation(
    donor_participant_id: str = "p2",
    *,
    query_atom_ids: list[int] | None = None,
) -> QueryCandidateAdaptation:
    """Build a QueryCandidateAdaptation for fixture."""
    return QueryCandidateAdaptation(
        donor_participant_id=donor_participant_id,
        query_atom_ids=query_atom_ids or [],
    )


# =====================================================================
# Invariant 1 (§14): donor_context_is_assumption = True
# =====================================================================

def test_donor_context_is_assumption():
    """Invariant 1: all inherited donor context is marked as assumption.

    InheritedDonorContext.is_assumption is locked to True by the schema
    (Literal[True]). The builder must populate inherited_donor_context with
    at least one entry, and every entry must carry is_assumption=True.
    Donor-derived context can NEVER be marked as a proven X→Y fact.
    """
    source = _minimal_source_ledger(
        role_assignments=[RoleAssignment(
            participant_id="p2",
            role=ParticipantRole.carrier,
        )],
    )
    ledger = build_candidate_skeleton(
        source, _adaptation(donor_participant_id="p2"),
        candidate_id="cand_001",
    )
    assert len(ledger.inherited_donor_context) >= 1
    for ctx in ledger.inherited_donor_context:
        assert ctx.is_assumption is True
        assert ctx.donor_reaction_id == source.reaction_evidence_id
        assert ctx.donor_participant_id == "p2"


# =====================================================================
# Invariant 2 (§14): source_ledger_link exists
# =====================================================================

def test_source_ledger_link_exists():
    """Invariant 2: source_ledger_id is non-empty and matches source ledger.

    The CandidateAnalogyLedger MUST link back to its SourceReactionLedger.
    source_ledger_id is a mandatory NonEmptyStr that must equal the
    source_ledger.ledger_id passed in — never empty, never fabricated.
    """
    source = _minimal_source_ledger(ledger_id="srl_link_test_42")
    ledger = build_candidate_skeleton(
        source, _adaptation(donor_participant_id="p1"),
        candidate_id="cand_001",
    )
    assert ledger.source_ledger_id  # non-empty
    assert ledger.source_ledger_id == "srl_link_test_42"
    assert ledger.source_ledger_id == source.ledger_id


# =====================================================================
# Invariant 3 (§14): candidate_id belongs current context
# =====================================================================

def test_candidate_id_belongs_current_context():
    """Invariant 3: candidate_id is the one provided by current context.

    The builder does NOT generate candidate_id (that would be generating a
    candidate, which is forbidden). The caller provides candidate_id from the
    current context; the builder echoes it back verbatim and validates it is
    non-empty. An empty candidate_id is rejected.
    """
    source = _minimal_source_ledger()
    ledger = build_candidate_skeleton(
        source, _adaptation(donor_participant_id="p1"),
        candidate_id="cand_context_007",
    )
    assert ledger.candidate_id == "cand_context_007"
    # Empty candidate_id rejected (NonEmptyStr contract)
    with pytest.raises((ValidationError, ValueError)):
        build_candidate_skeleton(
            source, _adaptation(donor_participant_id="p1"),
            candidate_id="",
        )


# =====================================================================
# Invariant 4 (§14): donor cofactor != proven X→Y cofactor
# =====================================================================

def test_donor_cofactor_not_proven_xy_cofactor():
    """Invariant 4: donor cofactors flow to unknown_actual_cofactors.

    The donor reaction may use NAD(P), O2, etc. as cofactors. These are
    DONOR facts, NOT proven X→Y facts. The candidate ledger must record them
    in ``unknown_actual_cofactors`` (inherited assumption), and the schema
    has NO field that claims cofactors are proven for X→Y.
    """
    source = _minimal_source_ledger(
        cofactor_changes=[
            CofactorChange(
                participant_id="p2",
                oxidized_form="NC(=O)c1ccc[n+]2",
                direction="unknown",
            ),
        ],
        role_assignments=[RoleAssignment(
            participant_id="p2",
            role=ParticipantRole.carrier,
        )],
    )
    ledger = build_candidate_skeleton(
        source, _adaptation(donor_participant_id="p2"),
        candidate_id="cand_001",
    )
    # Donor HAD cofactors (source fact)
    assert len(source.cofactor_changes) >= 1
    donor_cofactor_pids = {cc.participant_id for cc in source.cofactor_changes}
    # Candidate ledger records them as UNKNOWN for X→Y (not proven)
    assert len(ledger.unknown_actual_cofactors) >= 1
    for pid in donor_cofactor_pids:
        assert pid in ledger.unknown_actual_cofactors
    # Schema has NO "proven_cofactors" / "xy_cofactors" field — only unknown_*
    assert not hasattr(ledger, "proven_cofactors")
    assert not hasattr(ledger, "xy_cofactors")
    assert not hasattr(ledger, "actual_cofactors")


# =====================================================================
# Invariant 5 (§14): formal_balance_under_assumptions != observed balance
# =====================================================================

def test_formal_balance_under_assumptions_not_observed():
    """Invariant 5: formal_balance_under_assumptions is separate from observed.

    The source ledger's element_balance / charge_balance / balance_status
    record what the DONOR reaction actually observes. The candidate's
    formal_balance_under_assumptions is a SEPARATE object computed under
    donor-derived assumptions for X→Y. It must:
    - be non-None (populated)
    - carry assumption_notes explicitly labeling it as assumption-based
    - NOT be the same object as the source's observed balance
    - candidate_balance_status defaults to partial_or_unbalanced_source
      (assumption-based, not observed)
    """
    source = _minimal_source_ledger(
        balance_status=LedgerBalanceStatus.heavy_atom_balanced_with_implicit_h_e_policy,
    )
    ledger = build_candidate_skeleton(
        source, _adaptation(donor_participant_id="p1"),
        candidate_id="cand_001",
    )
    # formal_balance_under_assumptions is populated
    assert ledger.formal_balance_under_assumptions is not None
    fba = ledger.formal_balance_under_assumptions
    # Explicitly labeled as assumption-based
    notes = " ".join(fba.assumption_notes)
    assert "assumption" in notes.lower(), (
        f"assumption_notes must label the balance as assumption-based, "
        f"got: {fba.assumption_notes}"
    )
    # candidate_balance_status reflects assumption (default partial)
    assert ledger.candidate_balance_status == LedgerBalanceStatus.partial_or_unbalanced_source
    # The candidate balance status is NOT the source's observed status
    # (even when source is heavy_atom_balanced, candidate stays partial)
    assert ledger.candidate_balance_status != source.balance_status


# =====================================================================
# No-Y discipline (§14): skeleton does not generate Y / ranking / rationale
# =====================================================================

def test_no_y_generated():
    """Skeleton does NOT generate Y / ranking / LLM rationale.

    The candidate analogy ledger skeleton is a RECORD of assumptions, not a
    prediction. It must NOT carry:
    - product SMILES / canonical_product (Y generation)
    - ranking_score (candidate ranking)
    - llm_rationale / rationale (LLM rationale)
    - any Candidate object (the fixture candidate_id is a context handle,
      NOT a generated prediction)
    """
    source = _minimal_source_ledger()
    ledger = build_candidate_skeleton(
        source, _adaptation(donor_participant_id="p1"),
        candidate_id="cand_001",
    )
    # No Y (product SMILES) — ledger schema has no product field
    assert not hasattr(ledger, "canonical_product")
    assert not hasattr(ledger, "generated_product_smiles")
    assert not hasattr(ledger, "product_smiles")
    assert not hasattr(ledger, "predicted_product")
    # No ranking
    assert not hasattr(ledger, "ranking_score")
    assert not hasattr(ledger, "rank")
    # No LLM rationale
    assert not hasattr(ledger, "llm_rationale")
    assert not hasattr(ledger, "rationale")
    assert not hasattr(ledger, "explanation")
    # No Candidate object embedded (skeleton only)
    assert not hasattr(ledger, "candidate")
    # unknowns preserved as a list (not silently filled)
    assert isinstance(ledger.unknowns, list)
    # evidence_ids inherited from source (list, not fabricated)
    assert isinstance(ledger.evidence_ids, list)


# =====================================================================
# Edge: immutability — source_ledger and adaptation not mutated
# =====================================================================

def test_builder_does_not_mutate_inputs():
    """Builder must not mutate source_ledger or adaptation (immutability).

    Returns a new CandidateAnalogyLedger; inputs are left intact.
    """
    source = _minimal_source_ledger(
        cofactor_changes=[CofactorChange(participant_id="p2", direction="unknown")],
    )
    adaptation = _adaptation(donor_participant_id="p2")
    source_before = source.model_dump()
    adaptation_before = adaptation.model_dump()
    build_candidate_skeleton(source, adaptation, candidate_id="cand_001")
    assert source.model_dump() == source_before
    assert adaptation.model_dump() == adaptation_before


# =====================================================================
# Edge: unknowns preserved — donor stoichiometry → unknown_actual_stoichiometry
# =====================================================================

def test_donor_stoichiometry_flows_to_unknown():
    """Donor stoichiometry is NOT proven for X→Y.

    Donor stoichiometry entries flow to unknown_actual_stoichiometry
    (inherited assumption), preserving the no-fabrication discipline.
    """
    source = _minimal_source_ledger(
        stoichiometry=[
            StoichiometricEntry(participant_id="p1", coefficient=2, side="reactant"),
            StoichiometricEntry(participant_id="p2", coefficient=1, side="reactant"),
        ],
    )
    ledger = build_candidate_skeleton(
        source, _adaptation(donor_participant_id="p2"),
        candidate_id="cand_001",
    )
    assert len(ledger.unknown_actual_stoichiometry) >= 1
    donor_pids = {s.participant_id for s in source.stoichiometry}
    for pid in donor_pids:
        assert pid in ledger.unknown_actual_stoichiometry


# =====================================================================
# Edge: ledger_id is stable + content-addressed
# =====================================================================

def test_ledger_id_stable_and_content_addressed():
    """ledger_id is a stable hash of (source_ledger_id, candidate_id, version).

    Same inputs → same ledger_id. Different candidate_id → different ledger_id.
    """
    source = _minimal_source_ledger(ledger_id="srl_stable_001")
    adaptation = _adaptation(donor_participant_id="p1")
    l1 = build_candidate_skeleton(source, adaptation, candidate_id="cand_A")
    l2 = build_candidate_skeleton(source, adaptation, candidate_id="cand_A")
    l3 = build_candidate_skeleton(source, adaptation, candidate_id="cand_B")
    assert l1.ledger_id == l2.ledger_id  # deterministic
    assert l1.ledger_id != l3.ledger_id  # different candidate → different id
    assert l1.ledger_id.startswith("cal_")  # candidate analogy ledger prefix
